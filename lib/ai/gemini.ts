/**
 * Generates dynamic, hyper-localized multilingual crop guidance using Gemini.
 */
export async function generateGeminiCropGuidance(
  params: DynamicGuidanceParams
): Promise<CropGuidance & { source: "gemini"; timestamp: string }> {
  const systemInstruction = `You are AgriSurge AI Agronomist, a senior agricultural scientist specialized in Indian crops (Maharashtra, Vidarbha, Marathwada, Deccan plateau, and North India).
Provide highly accurate, scientifically backed, and actionable agronomic guidance for the specified crop, tailored precisely to the farm's soil, irrigation, and microclimate conditions.
Respond in valid JSON format only, matching the exact requested keys.
Provide all text in three languages:
- 'mr' (Marathi, authentic conversational yet scientific Marathi as spoken by Maharashtra farmers)
- 'hi' (Hindi, clear and practical Hindi)
- 'en' (English, professional agronomic English)
Do NOT include markdown formatting or backticks outside of the JSON.`;

  const prompt = `Generate comprehensive agronomic guidance for:
Crop: ${params.cropName} (${params.cropKey})
Location: District: ${params.district || "Ahmednagar"}, Village: ${params.village || "Local Farm"}
Soil Type: ${params.soilType || "Black Soil"}
Irrigation Method: ${params.irrigationType || "Rainfed"}
Farm Acreage: ${params.areaAcres || 2.5} acres
Current Weather: Temperature: ${params.temperatureC || 27}°C, Humidity: ${params.humidityPct || 65}%, Rainfall: ${params.rainfallMm || 110}mm

Return a JSON object with this exact shape:
{
  "whySuitable": { "mr": "...", "hi": "...", "en": "..." },
  "waterManagement": { "mr": "...", "hi": "...", "en": "..." },
  "fertilizerTiming": { "mr": "...", "hi": "...", "en": "..." },
  "growthStageCare": { "mr": "...", "hi": "...", "en": "..." },
  "weatherPrecautions": { "mr": "...", "hi": "...", "en": "..." },
  "keyRisks": { "mr": "...", "hi": "...", "en": "..." },
  "nextSteps": { "mr": "...", "hi": "...", "en": "..." }
}`;

  const rawJson = await callGemini(prompt, systemInstruction, 0.4);
  const parsed = extractJSON<CropGuidance>(rawJson);

  return {
    ...parsed,
    source: "gemini",
    timestamp: new Date().toISOString(),
  };
}

/**
 * Interactive Farmer AI Assistant Chat
 */
export interface FarmerChatContext {
  farmerName?: string;
  crop?: string;
  district?: string;
  soilType?: string;
  irrigationType?: string;
  temperatureC?: number;
  humidityPct?: number;
  rainfallMm?: number;
  language?: "mr" | "hi" | "en";
}

export async function askGeminiFarmerAssistant(
  question: string,
  context: FarmerChatContext,
  history: Array<{ role: "user" | "assistant"; text: string }> = []
): Promise<string> {
  const lang = context.language || "mr";
  const langName = lang === "mr" ? "Marathi (मराठी)" : lang === "hi" ? "Hindi (हिंदी)" : "English";

  const systemInstruction = `You are AgriSurge AI Advisor, a friendly, expert, and empathetic agricultural advisor.
You are assisting ${context.farmerName || "a respected farmer"} in ${context.district || "Maharashtra, India"}.
Farm Context:
- Target Crop: ${context.crop || "Agricultural Crops"}
- Soil: ${context.soilType || "Black Soil"}
- Irrigation: ${context.irrigationType || "Rainfed"}
- Local Temperature: ${context.temperatureC ?? 27}°C
- Humidity: ${context.humidityPct ?? 65}%
- Rainfall estimate: ${context.rainfallMm ?? 100}mm

Rules:
1. Always respond primarily in ${langName}, matching the farmer's preferred language. If they ask in another language, respond in that language.
2. Provide practical, low-cost, organic/sustainable and ICAR/Agricultural University-approved solutions.
3. Be respectful, encouraging, and clear (use bullet points and bold text where helpful).
4. If warning about pesticide or chemical usage, mention safety dosages clearly.`;

  let conversationHistory = "";
  if (history.length > 0) {
    conversationHistory =
      "Recent conversation:\n" +
      history.slice(-4).map((h) => `${h.role === "user" ? "Farmer" : "Assistant"}: ${h.text}`).join("\n") +
      "\n\n";
  }

  const prompt = `${conversationHistory}Farmer asks: "${question}"\n\nProvide direct, practical, and localized advice in ${langName}:`;

  return await callGemini(prompt, systemInstruction, 0.6);
}

