import { CropGuidance } from "@/lib/farmer/cropGuidance";

const GEMINI_API_KEY = process.env.GEMINI_API_KEY || "";
// Resilient model cascade: tries gemini-3.8-flash first, then gemini-3.7-flash, then gemini-flash-latest
const CANDIDATE_MODELS = [
  "gemini-2.5-flash",
  "gemini-3.5-flash",
  "gemini-3.8-flash",
  "gemini-3.7-flash",
  "gemini-flash-latest",
  "gemini-3.5-flash",
];

export function isGeminiAvailable(): boolean {
  return Boolean(GEMINI_API_KEY && GEMINI_API_KEY.trim().length > 0);
}

/**
 * Low-level text generation from Gemini with automated model cascade
 */
export async function callGemini(
  prompt: string,
  systemInstruction?: string,
  temperature: number = 0.5
): Promise<string> {
  if (!isGeminiAvailable()) {
    throw new Error("GEMINI_API_KEY is not configured.");
  }

  let lastError: Error | null = null;

  for (const model of CANDIDATE_MODELS) {
    try {
      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${GEMINI_API_KEY}`;

      const payload: any = {
        contents: [
          {
            parts: [{ text: prompt }],
          },
        ],
        generationConfig: {
          temperature,
          maxOutputTokens: 2048,
        },
      };

      if (systemInstruction) {
        payload.systemInstruction = {
          parts: [{ text: systemInstruction }],
        };
      }

      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });

      if (!response.ok) {
        const errorBody = await response.text();
        console.warn(`[Gemini API Warning] Model ${model} returned ${response.status}:`, errorBody.slice(0, 120));
        lastError = new Error(`Model ${model} failed (${response.status}): ${errorBody}`);
        continue; // Try next model in cascade
      }

      const result = await response.json();
      const text = result.candidates?.[0]?.content?.parts?.[0]?.text;

      if (!text) {
        lastError = new Error(`Model ${model} returned empty candidate content.`);
        continue;
      }

      return text.trim();
    } catch (err: any) {
      lastError = err;
      console.warn(`[Gemini API Cascade] Error with ${model}:`, err.message);
    }
  }

  throw lastError || new Error("All Gemini models in cascade failed.");
}

/**
 * Clean and parse JSON generated by Gemini (handles code block fences ```json ... ```)
 */
export function extractJSON<T>(rawText: string): T {
  let cleaned = rawText.trim();
  // Strip markdown code fences if present
  if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```(?:json)?\n?/, "").replace(/\n?```$/, "");
  }
  return JSON.parse(cleaned);
}

